#!/usr/bin/env python3
"""Generate stable Inno Setup preprocessor constants from product.json."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from scripts.build.validate_config import validate_product_config

ROOT = Path(__file__).resolve().parents[2]


def _quote(value: object) -> str:
    text = str(value)
    if '"' in text or "\n" in text or "\r" in text:
        raise ValueError(f"value cannot be represented in an Inno constant: {text!r}")
    return f'"{text}"'


def render(config: dict[str, object]) -> str:
    validate_product_config(config)
    product = config["product"]
    target = config["target"]
    assert isinstance(product, dict) and isinstance(target, dict)
    python = target["python"]
    assert isinstance(python, dict)
    constants = {
        "ProductName": product["name"],
        "Publisher": product["publisher"],
        "ProductVersion": product["version"],
        # Inno escapes a literal opening brace by doubling it. The directive
        # therefore receives the stable GUID-form AppId instead of a constant.
        "AppId": "{{" + str(product["app_id"]) + "}",
        "RegistryPath": product["registry_path"],
        "PythonVersion": python["version"],
        "PythonInstallerFilename": python["filename"],
        "OutputBase": (f"{product['output_basename']}-{product['version']}-windows-x64"),
    }
    lines = ["; Generated by scripts/build/generate_inno_config.py. Do not edit."]
    lines.extend(f"#define {name} {_quote(value)}" for name, value in constants.items())
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, default=ROOT / "config" / "product.json")
    parser.add_argument("--output", type=Path, default=ROOT / "installer" / "generated-config.iss")
    args = parser.parse_args(argv)
    config = json.loads(args.config.read_text(encoding="utf-8"))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(config), encoding="utf-8")
    print(f"Inno configuration written: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
